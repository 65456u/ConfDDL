export interface ConferenceDeadline {
  /** Calendar year of this submission deadline; may differ from conference edition */
  year: number;
  /** Month of the deadline using 1-12 */
  month: number;
  /** Day of the month using 1-31 */
  day: number;
  /** Hour of the day in 24-hour time */
  hour: number;
  /** Minute of the hour */
  minute: number;
  /** ISO 8601 timezone offset, e.g. +00:00, -12:00 */
  offset: string;
  /** Mark true when the schedule is based on historic cadence */
  estimated?: boolean;
}

export interface AcceptanceRate {
  /** Conference edition the published acceptance statistics describe */
  edition: number;
  /** Acceptance rate as a percentage, e.g. 24.5 for 24.5% */
  rate: number;
  /** Track or program scope of the statistic */
  scope: string;
  /** Official report or conference page supporting the value */
  sourceUrl: string;
  /** True when the official source describes the rate as approximate */
  approximate?: boolean;
  /** True when calculated from accepted and submitted counts in the source */
  calculated?: boolean;
  /** Official submission volume; may cover a broader scope than the rate */
  submissionCount?: number;
  /** Label clarifying the scope of the submission volume */
  submissionCountScope?: string;
  accepted?: number;
  submissions?: number;
}

